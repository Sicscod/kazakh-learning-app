-- ───────────── Profile on sign-up ─────────────

create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(user_id, display_name)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data->>'display_name'), ''), split_part(new.email, '@', 1))
  );
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ───────────── RPC: streak (spec §5.2) ─────────────

create function public.record_activity(p_local_date date)
returns table(streak int, last_active_date date)
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'not signed in' using errcode = 'insufficient_privilege';
  end if;

  return query
  update public.profiles p set
    streak = case
      when p.last_active_date is null or p_local_date > p.last_active_date + 1 then 1
      when p_local_date = p.last_active_date + 1 then p.streak + 1
      else p.streak                                   -- same day or earlier (clock skew)
    end,
    last_active_date = greatest(coalesce(p.last_active_date, p_local_date), p_local_date)
  where p.user_id = uid
  returning p.streak, p.last_active_date;
end $$;

-- ───────────── RPC: save one answer (spec §5.1) ─────────────

create function public.upsert_progress(p_word_id bigint, p_box int, p_due_at timestamptz, p_correct boolean)
returns void
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'not signed in' using errcode = 'insufficient_privilege';
  end if;
  if p_box < 0 or p_box > 5 then
    raise exception 'box out of range' using errcode = 'check_violation';
  end if;

  insert into public.word_progress as wp (user_id, word_id, box, due_at, correct_count, wrong_count, updated_at)
  values (uid, p_word_id, p_box, p_due_at, case when p_correct then 1 else 0 end, case when p_correct then 0 else 1 end, now())
  on conflict (user_id, word_id) do update set
    box = excluded.box,
    due_at = excluded.due_at,
    correct_count = wp.correct_count + excluded.correct_count,
    wrong_count = wp.wrong_count + excluded.wrong_count,
    updated_at = now();
end $$;

revoke execute on function public.record_activity(date) from public, anon;
revoke execute on function public.upsert_progress(bigint, int, timestamptz, boolean) from public, anon;
grant execute on function public.record_activity(date) to authenticated;
grant execute on function public.upsert_progress(bigint, int, timestamptz, boolean) to authenticated;
