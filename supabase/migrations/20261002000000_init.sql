-- Kazakh Learning App — MVP schema (spec: docs/superpowers/specs/2026-10-02-kazakh-app-mvp-design.md §6)

-- ───────────── Content (public read, no client writes) ─────────────

create table public.levels (
  code text primary key check (code in ('A1','A2','B1','B2','C1','C2')),
  sort int not null unique,
  is_available boolean not null default false,
  content_version int not null default 1
);

insert into public.levels(code, sort, is_available) values
  ('A1', 1, true), ('A2', 2, true),
  ('B1', 3, false), ('B2', 4, false), ('C1', 5, false), ('C2', 6, false);

create table public.topics (
  id bigint generated by default as identity primary key,
  level_code text not null references public.levels(code),
  slug text not null unique,
  sort int not null,
  icon text
);
create index topics_level_idx on public.topics(level_code, sort);

create table public.words (
  id bigint generated by default as identity primary key,
  topic_id bigint not null references public.topics(id) on delete cascade,
  kk text not null,
  example_kk text not null check (length(trim(example_kk)) > 0),
  sort int not null
);
create index words_topic_idx on public.words(topic_id, sort);

create table public.translations (
  entity_type text not null check (entity_type in ('topic','word','example')),
  entity_id bigint not null,
  lang text not null check (lang in ('kk','ru','en','zh')),
  text text not null check (length(trim(text)) > 0),
  primary key (entity_type, entity_id, lang)
);

-- ───────────── User data (owner only) ─────────────

create table public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  level_code text references public.levels(code),          -- null = onboarding not finished
  learning_lang text not null default 'ru' check (learning_lang in ('ru','en','zh')),
  ui_lang text not null default 'kk' check (ui_lang in ('kk','ru','en','zh')),
  streak int not null default 0 check (streak >= 0),
  last_active_date date,
  created_at timestamptz not null default now()
);

create table public.word_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  word_id bigint not null references public.words(id) on delete cascade,
  box int not null default 0 check (box between 0 and 5),
  due_at timestamptz not null default now(),
  correct_count int not null default 0,
  wrong_count int not null default 0,
  updated_at timestamptz not null default now(),
  primary key (user_id, word_id)
);
create index word_progress_due_idx on public.word_progress(user_id, due_at);

create table public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('user','assistant')),
  content text not null,
  created_at timestamptz not null default now()
);
create index chat_messages_user_idx on public.chat_messages(user_id, created_at);

create table public.content_reports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  word_id bigint not null references public.words(id) on delete cascade,
  comment text not null check (length(comment) <= 1000),
  created_at timestamptz not null default now()
);

